// Web Audio API synthesizers for soothing, dementia-friendly feedback in CogniCare
let audioCtx = null;

// Sound preference, remembered on this device. Sounds are on unless the person turns them off.
const SOUND_KEY = 'memory-lane:game-sound';
let soundOn = true;
try {
  soundOn = window.localStorage.getItem(SOUND_KEY) !== 'off';
} catch {
  // Storage can be blocked; sounds stay on for this visit.
}

export function isSoundOn() {
  return soundOn;
}

export function setSoundOn(next) {
  soundOn = Boolean(next);
  try {
    window.localStorage.setItem(SOUND_KEY, soundOn ? 'on' : 'off');
  } catch {
    // Persisting is best-effort only.
  }
}

function getAudioContext() {
  if (!soundOn) return null;
  if (!audioCtx && typeof window !== 'undefined') {
    const AudioContextClass = window.AudioContext || window.webkitAudioContext;
    if (AudioContextClass) {
      audioCtx = new AudioContextClass();
    }
  }
  if (audioCtx && audioCtx.state === 'suspended') {
    audioCtx.resume();
  }
  return audioCtx;
}

/**
 * Play a soothing gentle chime (positive confirmation)
 */
export function playGentleChime() {
  try {
    const ctx = getAudioContext();
    if (!ctx) return;

    const notes = [523.25, 659.25, 783.99]; // C5, E5, G5
    notes.forEach((freq, idx) => {
      const osc = ctx.createOscillator();
      const gain = ctx.createGain();

      osc.type = 'sine';
      osc.frequency.setValueAtTime(freq, ctx.currentTime + idx * 0.08);

      gain.gain.setValueAtTime(0, ctx.currentTime + idx * 0.08);
      gain.gain.linearRampToValueAtTime(0.12, ctx.currentTime + idx * 0.08 + 0.04);
      gain.gain.exponentialRampToValueAtTime(0.0001, ctx.currentTime + idx * 0.08 + 0.9);

      osc.connect(gain);
      gain.connect(ctx.destination);

      osc.start(ctx.currentTime + idx * 0.08);
      osc.stop(ctx.currentTime + idx * 0.08 + 0.95);
    });
  } catch {
    // Audio is optional; stay silent if it cannot play.
  }
}

/**
 * Play a soft tap/flip sound
 */
export function playCardFlip() {
  try {
    const ctx = getAudioContext();
    if (!ctx) return;

    const osc = ctx.createOscillator();
    const gain = ctx.createGain();

    osc.type = 'triangle';
    osc.frequency.setValueAtTime(320, ctx.currentTime);
    osc.frequency.exponentialRampToValueAtTime(180, ctx.currentTime + 0.08);

    gain.gain.setValueAtTime(0.08, ctx.currentTime);
    gain.gain.exponentialRampToValueAtTime(0.001, ctx.currentTime + 0.08);

    osc.connect(gain);
    gain.connect(ctx.destination);

    osc.start();
    osc.stop(ctx.currentTime + 0.09);
  } catch {
    // Audio is optional; stay silent if it cannot play.
  }
}

